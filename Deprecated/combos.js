function InitiateCombos()
    {
    InitiatePinkPool()
    var comboOrder = combo49ArrManualOrder;
    var terminate = false;
    var count = 0
    while(!terminate)
        {
        for(var i=0;i<comboOrder.length;i++)
            {
            if(Combo([2,1,0], comboOrder[i]))
                {
                count++;
                i--;
                break;
                }
            if(Combo([0,2,0], comboOrder[i]))
                {
                count++;
                i--;
                break;
                }
            if(Combo([0,1,1], comboOrder[i]))
                {
                count++;
                i--;
                break;
                }
            terminate = true;
            }
        }
    TextWindow.Print('Out of combos ' + count);
    }
    
function Combo(lowComboArr, highComboArr)
	{
    var fullComboArr = lowComboArr.concat(highComboArr);
	var pinksArr = JSON.parse(Orion.RegRead('PinkPool'));
	for(var i=0;i<fullComboArr.length;i++)
		{
		if(pinksArr[i] < fullComboArr[i])
			return false;
		}
	for(var i=0;i<fullComboArr.length;i++)
		{
		pinksArr[i] -= fullComboArr[i];
		}
	pinksArr[10]++;
	pinksArr[11]++;
	Orion.RegWrite('PinkPool', JSON.stringify(pinksArr));
	TextWindow.Open();
	TextWindow.Print(pinksArr + ' : ' + fullComboArr);
	return true;
	}